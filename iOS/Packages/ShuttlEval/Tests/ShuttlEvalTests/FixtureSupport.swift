extension PyValue {
    /// float / int / None(NaN).
    var dbl: Double { double ?? .nan }
    var dbls: [Double] { (list ?? []).map(\.dbl) }
    var v2s: [SIMD2<Double>] { (list ?? []).map { SIMD2(row: $0.dbls) } }
    var bools: [Bool]? { list?.map { $0.bool ?? false } }
    var strs: [String] { (list ?? []).compactMap(\.string) }
    var optV2s: [SIMD2<Double>?] { (list ?? []).map { $0.isNone ? nil : SIMD2(row: $0.dbls) } }

    /// Decode through JSON (NaN ⇄ null like every Shuttl fixture).
    func decode<T: Decodable>(_ type: T.Type) throws -> T {
        try JSONDecoder().decode(T.self, from: Data(pythonJSON().utf8))
    }

    /// `[[x, y, score], …]` per frame, keeping NaN-score candidates (Python keeps them).
    var candidates: [[ShuttleCandidate]] {
        (list ?? []).map { f in (f.list ?? []).map { c in
            let v = c.dbls
            return ShuttleCandidate(x: v[0], y: v[1], score: v[2])
        } }
    }
}

/// Exact parity: same keys / order / types, floats bit-identical (None ≡ non-finite).
func assertSamePy(_ actual: PyDict, _ expected: PyValue, _ msg: @autoclosure () -> String = "",
                  relTol: Double = 0, file: StaticString = #filePath, line: UInt = #line) {
    let d = ReportCompare.compare(.dict(actual), expected, relTol: relTol, skip: [])
    XCTAssert(d.ok, "\(msg()):\n" + d.mismatches.joined(separator: "\n"), file: file, line: line)
}

/// Bit equality (NaN == NaN).
func sameBits(_ a: Double, _ b: Double) -> Bool { a == b || (a.isNaN && b.isNaN) }

func assertBits(_ a: [Double], _ b: [Double], _ msg: @autoclosure () -> String = "",
                file: StaticString = #filePath, line: UInt = #line) {
    XCTAssertEqual(a.count, b.count, "length \(msg())", file: file, line: line)
    let bad = zip(a, b).enumerated().filter { !sameBits($0.element.0, $0.element.1) }
    XCTAssert(bad.isEmpty, "\(msg()): \(bad.count) of \(a.count) differ, first \(bad.prefix(3).map { "[\($0.offset)] \($0.element.0) vs \($0.element.1)" })",
              file: file, line: line)
}

/// Run the CLI quietly.
func runBench(_ argv: [String]) async throws -> (report: BenchReport, diff: ReportDiff?, text: String) {
    final class Sink: @unchecked Sendable { var text = "" }
    let sink = Sink()
    var cli = BenchCLI(backend: backendRoot)
    cli.print = { sink.text += $0 }
    let (r, d) = try await cli.run(argv)
    return (r, d, sink.text)
}
