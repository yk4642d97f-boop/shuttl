/// URL of a fixture written by backend/scripts/swift_fixtures/eval.py.
func fixtureURL(_ name: String, ext: String = "json") throws -> URL {
    try XCTUnwrap(Bundle.module.url(forResource: name, withExtension: ext, subdirectory: "Fixtures"),
                  "missing fixture \(name).\(ext) — run `.venv/bin/python -m scripts.swift_fixtures.eval` in backend/")
}

func pyFixture(_ name: String) throws -> PyValue { try PyJSON.load(try fixtureURL(name)) }

